#!/usr/bin/env python3
"""Generates AirwinDocs.generated.cpp from the vendored awpdoc/*.txt files.

Upstream airwin2rack bundles these as a CMakeRC resource library, which would
require an app-bundle resource in Loopbacker. Instead we embed each doc as a
base64 blob in a generated C++ translation unit, decoded on first lookup.
Base64 sidesteps C++ string-literal escaping entirely (quotes, backslashes,
non-ASCII punctuation Airwindows docs are full of).

Usage: python3 generate_airwin_docs.py
Run from anywhere; paths are resolved relative to this script's location.
Re-run after updating awpdoc/*.txt (e.g. after re-vendoring a newer
airwin2rack commit) and commit the regenerated .cpp.
"""

import base64
import pathlib

SCRIPT_DIR = pathlib.Path(__file__).resolve().parent
TARGET_DIR = SCRIPT_DIR.parent
DOC_DIR = TARGET_DIR / "awpdoc"
OUTPUT = TARGET_DIR / "AirwinDocs.generated.cpp"

HEADER = """// Generated by Scripts/generate_airwin_docs.py from awpdoc/*.txt. Do not edit by hand.
#include "AirwinDocs.generated.h"

#include <string>
#include <unordered_map>

namespace {
std::string base64Decode(const char *data)
{
    static const std::string table =
        "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    std::string out;
    int val = 0, bits = -8;
    for (const char *p = data; *p; ++p)
    {
        unsigned char c = static_cast<unsigned char>(*p);
        if (c == '=' || c == '\\n' || c == '\\r')
            continue;
        auto pos = table.find(static_cast<char>(c));
        if (pos == std::string::npos)
            continue;
        val = (val << 6) + static_cast<int>(pos);
        bits += 6;
        if (bits >= 0)
        {
            out.push_back(static_cast<char>((val >> bits) & 0xFF));
            bits -= 8;
        }
    }
    return out;
}

const std::unordered_map<std::string, const char *> &docTable()
{
    static const std::unordered_map<std::string, const char *> table = {
"""

FOOTER = """    };
    return table;
}
} // namespace

std::string airwinDocTextFor(const std::string &name)
{
    const auto &table = docTable();
    auto it = table.find(name);
    if (it == table.end())
        return std::string();
    return base64Decode(it->second);
}
"""


def main() -> None:
    entries = []
    for path in sorted(DOC_DIR.glob("*.txt")):
        name = path.stem
        encoded = base64.b64encode(path.read_bytes()).decode("ascii")
        # Wrap long literals so no single line is unreasonably long.
        chunks = [encoded[i:i + 100] for i in range(0, len(encoded), 100)]
        literal = '"' + '" "'.join(chunks) + '"' if chunks else '""'
        entries.append(f'        {{"{name}", {literal}}},')

    with OUTPUT.open("w") as f:
        f.write(HEADER)
        f.write("\n".join(entries))
        f.write("\n")
        f.write(FOOTER)

    print(f"Wrote {OUTPUT} ({len(entries)} docs)")


if __name__ == "__main__":
    main()
